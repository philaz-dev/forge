export interface AnimalSeed {
  slug: string;
  name: string;
  species: Species;
  breed: string;
  sex: Sex;
  neutered: boolean;
  /** `YYYY-MM` */
  birth: string;
  owner: number;
  kg: number;
  /** Évolution de poids moyenne en kg / an (historique généré). */
  trend?: number;
  /** Jours écoulés depuis la dernière consultation. */
  visit: number;
  /** Jours avant la prochaine échéance vaccinale (négatif = en retard). */
  vd: number;
  /** Jours avant la prochaine échéance antiparasitaire. */
  pd: number;
  /** Mois écoulés depuis le dernier bilan / analyse (absent = jamais). */
  bilan?: number;
  /** Mois écoulés depuis le dernier contrôle dentaire. */
  dental?: number;
  coat: CoatKey;
  /* surcharges pour les fiches « vitrine » */
  visitDate?: string;
  weights?: [string, number][];
  ctrlDays?: number;
  postOp?: { label: string; date: string; follow: string };
  pending?: { label: string; since: string; due: string };
  allergies?: string[];
  diet?: string;
  info?: string;
  treatments?: { name: string; detail: string }[];
  /** Fixe la date du dernier bilan (ISO) pour les fiches vitrine. */
  bilanDate?: string;
}

